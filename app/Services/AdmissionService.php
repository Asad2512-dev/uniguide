    /**
     * Get filtered scholarships with pagination.
     */
    public function getScholarships(array $filters = [], string $sort = 'deadline_asc', int $perPage = 6, int $page = 1): array
    {
        $items = collect($this->scholarships);

        if (! empty($filters['q'])) {
            $q = strtolower(trim($filters['q']));
            $items = $items->filter(function ($s) use ($q) {
                return str_contains(strtolower($s['title']), $q) ||
                       str_contains(strtolower($s['provider']), $q) ||
                       str_contains(strtolower($s['coverage']), $q) ||
                       str_contains(strtolower($s['applicable_universities']), $q);
            });
        }

        if (! empty($filters['type']) && $filters['type'] !== 'all') {
            $items = $items->where('type', $filters['type']);
        }

        if (! empty($filters['status']) && $filters['status'] !== 'all') {
            $items = $items->where('status', $filters['status']);
        }

        // Sort items
        $items = match ($sort) {
            'deadline_desc' => $items->sortByDesc('deadline_date'),
            'title_asc' => $items->sortBy('title'),
            default => $items->sortBy('deadline_date'),
        };

        $total = $items->count();
        $totalPages = max(1, (int) ceil($total / $perPage));
        $page = max(1, min($page, $totalPages));
        $offset = ($page - 1) * $perPage;
        $paginatedItems = $items->slice($offset, $perPage)->values()->all();

        return [
            'data' => $paginatedItems,
            'total' => $total,
            'per_page' => $perPage,
            'current_page' => $page,
            'total_pages' => $totalPages,
            'from' => $total > 0 ? $offset + 1 : 0,
            'to' => min($offset + $perPage, $total),
        ];
    }

    /**
     * Get single scholarship by slug.
     */
    public function getScholarshipBySlug(string $slug): ?array
    {
        return collect($this->scholarships)->firstWhere('slug', $slug);
    }

